/** 곧은 몫을 말로 */
export function straightWord(p) {
  if (p >= 90) return '테두리가 거의 자로 그은 선입니다';
  if (p >= 75) return '반듯한 쪽에 가깝습니다';
  if (p >= 60) return '곧은 변과 굽은 변이 섞여 있습니다';
  if (p >= 45) return '굽은 구간이 제법 많습니다';
  return '자로 그은 선이 드문 테두리입니다';
}
/** 가장 긴 직선을 말로 */
export function longWord(m) {
  if (m >= 3000) return '한 번도 꺾이지 않고 3km 넘게 뻗는 변을 품고 있습니다';
  if (m >= 1500) return '끊기지 않고 1km 넘게 이어지는 변이 있습니다';
  if (m >= 700) return '제법 긴 직선 변을 하나 갖고 있습니다';
  return '길게 뻗는 직선 변이 없습니다';
}
/** 꺾임 수를 말로 */
export function cornerWord(n) {
  if (n === 0) return '크게 꺾이는 모서리가 하나도 없습니다';
  if (n <= 3) return '모서리가 몇 개 되지 않습니다';
  if (n <= 10) return '모서리가 적당히 있습니다';
  if (n <= 25) return '모서리가 많아 윤곽이 자잘합니다';
  return '모서리가 아주 많아 윤곽이 톱니처럼 잘게 갈라집니다';
}
/** 꼭짓점 밀도를 말로 */
export function denseWord(d) {
  if (d < 4) return '선을 적은 점으로 잡아 둔 단순한 윤곽입니다';
  if (d < 8) return '윤곽을 그리는 점이 보통 정도로 찍혀 있습니다';
  if (d < 14) return '윤곽선에 점이 촘촘히 찍혀 있습니다';
  return '점이 아주 빽빽해 선이 거의 곡선처럼 보입니다';
}
/** 땅 넓이를 길 찾기 쪽으로 */
export function reachWord(a) {
  if (a < 1) return '한쪽 끝에서 반대쪽까지 걸어도 금방입니다';
  if (a < 3) return '천천히 걸으면 건너편에 닿습니다';
  if (a < 10) return '걸어서 가로지르기에는 넓어 차를 쓰게 됩니다';
  if (a < 30) return '같은 이름 안에서도 차로 움직여야 합니다';
  return '한 이름 안에서도 끝과 끝이 멀어 이동만으로 한참입니다';
}

